-- Bucket público para fotos dos integrantes. Upload, alteração e exclusão exigem login autenticado.
insert into storage.buckets (id, name, public)
values ('member-photos', 'member-photos', true)
on conflict (id) do update set public = true;

drop policy if exists "public read member photos" on storage.objects;
create policy "public read member photos" on storage.objects for select using (bucket_id = 'member-photos');
drop policy if exists "admin upload member photos" on storage.objects;
create policy "admin upload member photos" on storage.objects for insert to authenticated with check (bucket_id = 'member-photos');
drop policy if exists "admin update member photos" on storage.objects;
create policy "admin update member photos" on storage.objects for update to authenticated using (bucket_id = 'member-photos') with check (bucket_id = 'member-photos');
drop policy if exists "admin delete member photos" on storage.objects;
create policy "admin delete member photos" on storage.objects for delete to authenticated using (bucket_id = 'member-photos');
