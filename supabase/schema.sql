create extension if not exists pgcrypto;

create table if not exists public.members (
  id uuid primary key default gen_random_uuid(),
  member_code text,
  nick text not null,
  role text not null default 'Membro',
  specialty text not null default 'Rifleman',
  rank text not null default 'A DEFINIR',
  rank_code text not null default 'RANK-001',
  kd numeric,
  status text not null default 'offline' check (status in ('online','offline')),
  avatar_url text,
  social_url text,
  featured boolean not null default false,
  active boolean not null default true,
  joined_at date,
  created_at timestamptz not null default now()
);

-- Permite reaplicar este arquivo em uma base criada antes do novo sistema de elenco.
alter table public.members add column if not exists member_code text;
alter table public.members add column if not exists rank_code text not null default 'RANK-001';
alter table public.members add column if not exists status text not null default 'offline';
alter table public.members add column if not exists joined_at date;

create table if not exists public.clan_ranks (
  id bigint generated by default as identity primary key,
  code text unique,
  nome text not null default 'A DEFINIR',
  nivel text not null default 'A DEFINIR',
  imagem text,
  descricao text,
  ordem int not null default 0,
  created_at timestamptz not null default now()
);
alter table public.clan_ranks add column if not exists code text;

create table if not exists public.news (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  tag text not null default 'INTEL',
  excerpt text,
  body text,
  published_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.media (
  id uuid primary key default gen_random_uuid(),
  type text not null,
  title text not null,
  url text,
  thumbnail_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.events (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  starts_at timestamptz,
  opponent text,
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.clan_stats (
  id bigint generated by default as identity primary key,
  key text unique not null,
  value int not null default 0,
  suffix text not null default '',
  label text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.recruitment_requests (
  id uuid primary key default gen_random_uuid(),
  nick text not null,
  rank text,
  age int not null,
  schedule text,
  experience text,
  discord text not null,
  motivation text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);

